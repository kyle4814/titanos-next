// build_sw.mjs (T19): writes sw.js into the portal folder. The service worker caches the shell, assets, engine, the data files the advisor
// needs, the rule ledger and the tile and stone product files, so the finder, calculator and advisor work with the network off after one visit.
// The cache name carries a hash of every cached file, so any data change makes a new cache. PDFs and other hosts are never cached.
// No background sync, no push, no analytics. Re-run after merging other blocks so their new files are listed.
// usage: node build_sw.mjs [portalDir]
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const PORTAL = process.argv[2] || path.join(HERE, '..', '..', 'public', 'demo', 'sika-210c0c');

function walk(dir, rel = '') {
  const out = [];
  for (const e of fs.readdirSync(path.join(dir, rel), { withFileTypes: true })) {
    const r = rel ? rel + '/' + e.name : e.name;
    if (e.isDirectory()) out.push(...walk(dir, r)); else out.push(r);
  }
  return out;
}

// wave 2: the data quality page (its JSON is network only, like data/gift/) is not needed offline, so its two files stay out of the 8 MB cache
// the sales engine (quote request) is fetched on demand and stays out of the cache for the same reason: the 8 MB budget had 903 B left after the three-lane merge; offline, asking for a quote says so
const NET_ONLY = /^assets\/(lib\/data-quality\.js|dq\.css|actions\/quote\.js|actions\/quote_ui\.js|quote\.css|brain\/rules(_read|_plan)?\.js)$/; // brain/rules*.js (the plan engine) reads data/brain/rules/*.json shards that are never cached, so it cannot run offline: 78 KB out of the cache

export function listing() {
  const files = ['index.html'];
  files.push(...walk(PORTAL, 'assets').filter((f) => !/\.(map|md)$/.test(f) && !f.startsWith('assets/img/') && !NET_ONLY.test(f)));  // product pictures load on demand, never precached
  const data = fs.readdirSync(path.join(PORTAL, 'data'), { withFileTypes: true });
  // wave 2: the 1.1 MB rule ledger (data/rules.json, read only by the Rule ledger page, which shows "not available" when the fetch fails) stays network only so the cache holds the 8 MB budget
  for (const e of data) if (e.isFile() && e.name.endsWith('.json') && e.name !== 'rules.json') files.push('data/' + e.name);
  for (const d of ['knowledge', 'systems']) if (fs.existsSync(path.join(PORTAL, 'data', d))) files.push(...walk(PORTAL, 'data/' + d).filter((f) => f.endsWith('.json'))); // data/sales (contact routes) is fetched with the quote engine, network only
  // tile and stone product pages only (the 37 files); other products need the network
  for (const f of fs.readdirSync(path.join(PORTAL, 'data', 'p'))) {
    const p = JSON.parse(fs.readFileSync(path.join(PORTAL, 'data', 'p', f), 'utf8'));
    if (/tile-stone/.test(p.category || '')) {
      files.push('data/p/' + f);
      for (const extra of ['data/k/' + f, 'data/finder/r/' + f]) if (fs.existsSync(path.join(PORTAL, extra))) files.push(extra); // apply/data (rates, times, safety) and apply/finder (calculator) files of the same product
    }
  }
  for (const idx of ['data/k/_index.json', 'data/finder/r/index.json']) if (fs.existsSync(path.join(PORTAL, idx))) files.push(idx);
  // the Specification tab (413 products, 5.8 MB) needs the network: left out of the offline cache to stay under the 8 MB target; the product page hides the tab offline
  return [...new Set(files)].sort();
}

export function build() {
  const files = listing();
  const h = crypto.createHash('sha1'); let bytes = 0;
  for (const f of files) { const b = fs.readFileSync(path.join(PORTAL, f)); h.update(f).update(b); bytes += b.length; }
  const hash = h.digest('hex').slice(0, 10);
  const src = `// sw.js (T19): offline mode for tile and stone. Generated by sika-demo-qa/build_sw.mjs, do not edit by hand.
// Scope is this folder. Caches the shell, assets, advisor data and the tile and stone product files. Never PDFs, never other hosts.
// No background sync, no push, no analytics. Cache name = prefix + hash of every cached file.
const PREFIX = 'sika-demo-210c0c-';
const CACHE = PREFIX + '${hash}';
const FILES = ${JSON.stringify(files)};
const BYTES = ${bytes};

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    // 'reload' so the browser's own HTTP cache cannot hand us a stale copy
    await Promise.all(FILES.map(async (f) => { const r = await fetch(new Request(f, { cache: 'reload' })); if (!r.ok) throw new Error(f + ': HTTP ' + r.status); await cache.put(f, r); }));
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    for (const k of await caches.keys()) if (k.startsWith(PREFIX) && k !== CACHE) await caches.delete(k);
    await self.clients.claim();
    const all = await self.clients.matchAll({ includeUncontrolled: true });
    for (const c of all) c.postMessage({ type: 'sika-offline', state: 'ready', cache: CACHE, files: FILES.length, bytes: BYTES });
  })());
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const hit = await cache.match(req, { ignoreSearch: true });
    if (hit) return hit;
    try { return await fetch(req); } catch (e) {
      if (req.mode === 'navigate') { const shell = await cache.match('index.html'); if (shell) return shell; }
      return new Response('Not available offline', { status: 503, statusText: 'Not available offline' });
    }
  })());
});

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'sika-offline-status') event.source.postMessage({ type: 'sika-offline', state: 'ready', cache: CACHE, files: FILES.length, bytes: BYTES });
});
`;
  return { src, hash, files, bytes };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const r = build();
  fs.writeFileSync(path.join(PORTAL, 'sw.js'), r.src);
  console.log(`sw.js: cache sika-demo-210c0c-${r.hash}, ${r.files.length} files, ${r.bytes} bytes (${(r.bytes / 1048576).toFixed(2)} MB)`);
}
