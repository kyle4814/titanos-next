// Reversible auto-fix. Only SAFE edits are automatic: they keep every existing mechanism and
// tighten a qualifier, merge duplicates, or publish a monitor-only record. Anything that needs
// knowledge we do not have (which mail senders exist, a DKIM key, a DS record, a policy host) is
// a guided quest the owner applies, and it is proven the same way: by a re-scan.
// Every apply stores the exact previous record set, so undo is exact.
import type { DnsWriter } from "./dnsw.ts";
import { tag, isSpfRecord, spfInfo, SPF_LOOKUP_LIMIT } from "../../../lib/guestscan/scan.ts";

export interface Edit { name: string; kind: "txt" | "mx" | "ds"; before: string[]; after: string[] }
export interface Plan { check: string; auto: boolean; summary: string; edits: Edit[]; reason?: string }

const first = (a: string[], p: string) => a.filter((r) => r.toLowerCase().startsWith(p));
function mergeSpf(recs: string[]): string {
  const mech = new Set<string>();
  for (const r of recs) for (const t of r.trim().split(/\s+/).slice(1)) { if (/^[+\-~?]*all$/i.test(t)) continue; mech.add(t); }
  return ["v=spf1", ...mech, "-all"].join(" ");
}
export async function planFor(check: string, domain: string, z: DnsWriter): Promise<Plan> {
  const guided = (summary: string, reason: string): Plan => ({ check, auto: false, summary, edits: [], reason });
  if (check === "SPF") {
    const all = await z.getTxt(domain); const spf = all.filter(isSpfRecord);
    if (!spf.length) return guided("Publish an SPF record listing your senders", "We cannot know which services send your mail; publishing a guess would block real mail.");
    // Guards (R-C3): appending -all next to redirect= makes receivers ignore the redirect and hard-fail every
    // sender behind it; merging records can push the total past the 10-lookup limit (permerror). Both are guided, no DNS write.
    const infos = spf.map(spfInfo);
    if (infos.some((i) => i.redirect)) return guided("Your SPF uses redirect=; edit it by hand", "A redirect= record must not get an -all added: receivers would ignore the redirect and reject mail from every sender behind it. Change it at the redirect target or list the senders directly.");
    if (infos.some((i) => i.unknown.length || i.ptr)) return guided("Your SPF has terms we will not rewrite; edit it by hand", "It contains ptr or terms receivers cannot read; we will not guess what you meant.");
    const merged = mergeSpf(spf);
    const mergedLookups = spfInfo(merged).lookups;
    if (mergedLookups > SPF_LOOKUP_LIMIT) return guided(`Your SPF would need ${mergedLookups} DNS lookups; trim it by hand`, `SPF allows ${SPF_LOOKUP_LIMIT} lookups. Merging your records would exceed that and receivers would ignore the whole record. Remove unused senders or use ip4/ip6 ranges.`);
    if (merged === "v=spf1 -all") return guided("Your SPF names no senders", "Changing it to -all would block all your mail; add your mail providers first.");
    return { check, auto: true, summary: `Keep your senders, end SPF with -all (${spf.length > 1 ? "merge " + spf.length + " records into one" : "tighten the ending"})`, edits: [{ name: domain, kind: "txt", before: all, after: [...all.filter((r) => !isSpfRecord(r)), merged] }] };
  }
  if (check === "DMARC") {
    const name = `_dmarc.${domain}`; const all = await z.getTxt(name); const d = first(all, "v=dmarc1");
    if (!d.length) return { check, auto: true, summary: "Publish a monitor-only DMARC record (p=none) with reporting", edits: [{ name, kind: "txt", before: all, after: [`v=DMARC1; p=none; rua=mailto:dmarc@${domain}; pct=100`] }] };
    const keep = d.length > 1 ? d.sort((a, b) => rank(b) - rank(a))[0] : d[0];
    const p = tag(keep, "p"), pct = tag(keep, "pct");
    if (d.length > 1) return { check, auto: true, summary: "Keep the strongest DMARC record, remove the others", edits: [{ name, kind: "txt", before: all, after: [keep] }] };
    if (p === "reject" && /^\d+$/.test(pct) && Number(pct) < 100) return { check, auto: true, summary: "Raise DMARC reject to pct=100", edits: [{ name, kind: "txt", before: all, after: [keep.replace(/pct=\d+/i, "pct=100")] }] };
    if (p === "quarantine" || p === "none" || !p) return guided(`Move DMARC from p=${p || "none"} to the next step`, "Tightening DMARC can block real mail until your reports look clean; the owner confirms when.");
  }
  if (check === "DKIM") return guided("Turn on DKIM signing at your mail provider", "The key is generated by your mail provider; we cannot invent it.");
  if (check === "DNSSEC") return guided("Switch DNSSEC on at your DNS host and add the DS record at your registrar", "Needs your registrar.");
  if (check === "MX") return guided("Add the MX records from your mail provider", "We cannot know your provider.");
  if (check === "MTA-STS") return guided("Host an MTA-STS policy and publish its TXT record", "Needs a web host for the policy file.");
  return guided("No automatic fix", "unknown check");
}
const rank = (r: string) => ({ reject: 3, quarantine: 2, none: 1 } as Record<string, number>)[tag(r, "p")] ?? 0;

export async function applyEdits(z: DnsWriter, edits: Edit[]): Promise<void> {
  for (const e of edits) { if (e.kind === "txt") await z.setTxt(e.name, e.after); else if (e.kind === "mx") await z.setMx(e.name, e.after); else await z.setDs(e.name, e.after.length > 0); }
}
export async function revertEdits(z: DnsWriter, edits: Edit[]): Promise<void> {
  for (const e of [...edits].reverse()) { if (e.kind === "txt") await z.setTxt(e.name, e.before); else if (e.kind === "mx") await z.setMx(e.name, e.before); else await z.setDs(e.name, e.before.length > 0); }
}
