// Read-only index of findings in website-chain FILL_*_RECEIPT.md files.
// Usage: node scripts/receipt_findings_index.mjs [--receipts DIR] [--briefs DIR] [--out FILE]
// Coverage match method: "id-ref" (finding names a brief's fNN id) or "keyword" (>=2 distinct
// content tokens of a brief id appear in the finding text). Own-receipt brief never counts.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const MARKERS = [
  { kind: "NEW FINDING", rx: /NEW FINDING/i, unfixed: true },
  { kind: "NOT FIXED", rx: /NOT FIXED/i, unfixed: true },
  { kind: "Candidate next row", rx: /Candidate next row/i, unfixed: true },
  { kind: "WOULD-FLIP", rx: /WOULD-FLIP/i, unfixed: false },
];
const STOP = new Set(["the", "and", "for", "with", "from", "into", "that", "this", "test", "tests", "suite", "wire", "gate", "plan", "mock"]);
const LIVE_RX = /\b(live|deploy|production|real (?:d1|stripe|cloudflare)|miniflare|remote|DNS|GATE[1-5]|card)\b/i;

export function receiptId(file) { return path.basename(file).replace(/^FILL_/, "").replace(/_RECEIPT\.md$/, ""); }
export function chunkOf(id, text) {
  const m = id.match(/(?:^|_)c(\d{1,2})(?:_|$)/);
  if (m && +m[1] >= 1 && +m[1] <= 10) return "c" + +m[1];
  const t = text.split("\n").slice(0, 12).join(" ").match(/\bchunk\s*c(\d{1,2})\b/i);
  if (t && +t[1] >= 1 && +t[1] <= 10) return "c" + +t[1];
  return "unassigned";
}
export function briefTokens(id) {
  return id.split("_").filter((t) => t.length >= 4 && !/^f\d+$/.test(t) && !/^c\d+$/.test(t) && !STOP.has(t.toLowerCase())).map((t) => t.toLowerCase());
}
export function parseReceipt(file, content) {
  const id = receiptId(file), lines = content.split("\n"), out = [];
  lines.forEach((ln, i) => {
    for (const m of MARKERS) if (m.rx.test(ln)) { out.push({ kind: m.kind, unfixed: m.unfixed, line: i + 1, text: ln.trim() }); break; }
  });
  let last = lines.length - 1; while (last >= 0 && !lines[last].trim()) last--;
  const fin = last >= 0 ? lines[last].trim() : "";
  if (/^\S+\s+(PARTIAL|FAILED)\b/.test(fin)) out.push({ kind: "PARTIAL/FAILED final", unfixed: true, line: last + 1, text: fin });
  return { id, chunk: chunkOf(id, content), findings: out.map((f) => ({ ...f, receipt: file, id })) };
}
export function coverage(finding, briefIds) {
  const txt = finding.text.toLowerCase(), hits = [];
  const refs = new Set((finding.text.match(/\bf\d{1,3}\b/gi) || []).map((s) => s.toLowerCase()));
  for (const b of briefIds) {
    if (b === finding.id) continue;
    const fid = b.split("_")[0].toLowerCase();
    if (refs.has(fid) && fid !== finding.id.split("_")[0].toLowerCase()) { hits.push({ brief: b, method: "id-ref" }); continue; }
    const tk = [...new Set(briefTokens(b))].filter((t) => txt.includes(t));
    if (tk.length >= 2) hits.push({ brief: b, method: "keyword(" + tk.join("+") + ")" });
  }
  return hits;
}
export function buildIndex(receiptsDir, briefsDir) {
  const files = fs.readdirSync(receiptsDir).filter((f) => /^FILL_.*_RECEIPT\.md$/.test(f)).sort();
  const briefIds = fs.existsSync(briefsDir) ? fs.readdirSync(briefsDir).filter((f) => f.endsWith(".md")).map((f) => f.slice(0, -3)) : [];
  const rows = [];
  for (const f of files) {
    const p = path.join(receiptsDir, f), r = parseReceipt(p, fs.readFileSync(p, "utf8"));
    for (const fd of r.findings) rows.push({ ...fd, chunk: r.chunk, covered: coverage(fd, briefIds) });
  }
  return { files: files.length, briefs: briefIds.length, rows };
}
export function summarise(idx) {
  const chunks = {};
  for (const r of idx.rows) {
    const c = (chunks[r.chunk] ??= { total: 0, unfixed: 0, uncovered: 0, byKind: {}, pendingLive: 0 });
    c.total++; c.byKind[r.kind] = (c.byKind[r.kind] || 0) + 1;
    if (r.unfixed) { c.unfixed++; if (!r.covered.length) c.uncovered++; }
    if (r.kind === "WOULD-FLIP" && LIVE_RX.test(r.text)) c.pendingLive++;
  }
  const un = idx.rows.filter((r) => r.unfixed);
  return { chunks, unfixed: un.length, uncovered: un.filter((r) => !r.covered.length).length };
}
const ORDER = [...Array.from({ length: 10 }, (_, i) => "c" + (i + 1)), "unassigned"];
export function render(idx) {
  const s = summarise(idx), L = [];
  L.push("# Receipt findings index", "", "Generated by `scripts/receipt_findings_index.mjs` (read-only over receipts). Do not edit by hand.", "",
    `Scanned ${idx.files} FILL_*_RECEIPT.md files, ${idx.briefs} brief ids. Markers: NEW FINDING, NOT FIXED, Candidate next row, WOULD-FLIP, PARTIAL/FAILED final line.`,
    "Chunk comes from the cN token in the receipt id, else a 'chunk cN' mention in its first 12 lines, else unassigned.",
    "Coverage method: id-ref (finding text names another brief's fNN id) or keyword (>=2 distinct id tokens of a brief appear in the finding text). Heuristic only: a keyword match is not proof the brief fixes it. Own-receipt brief excluded.",
    "Unfixed = NEW FINDING + NOT FIXED + Candidate next row + PARTIAL/FAILED final. WOULD-FLIP lines are limits, counted separately.", "",
    "## Counts per chunk", "", "| chunk | markers | unfixed | unfixed with no brief match | WOULD-FLIP needing live (PENDING LIVE) |", "|---|---|---|---|---|");
  for (const c of ORDER) if (s.chunks[c]) { const x = s.chunks[c]; L.push(`| ${c} | ${x.total} | ${x.unfixed} | ${x.uncovered} | ${x.pendingLive} |`); }
  L.push("", `TOTAL unfixed ${s.unfixed}, of which not covered by any brief id (keyword/id-ref method): ${s.uncovered}`, "");
  for (const c of ORDER) {
    const rs = idx.rows.filter((r) => r.chunk === c); if (!rs.length) continue;
    L.push(`## ${c}`, "");
    for (const r of rs) {
      const cov = r.unfixed ? (r.covered.length ? "covered by " + r.covered.map((h) => `${h.brief} [${h.method}]`).join(", ") : "NO BRIEF MATCH") : "limit";
      const live = r.kind === "WOULD-FLIP" && LIVE_RX.test(r.text) ? " PENDING LIVE;" : "";
      L.push(`- [${r.kind}] ${r.receipt}:${r.line}; ${cov};${live} ${r.text.slice(0, 160).replace(/\|/g, "/")}`);
    }
    L.push("");
  }
  return L.join("\n");
}
