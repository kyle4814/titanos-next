// Builds the data the actions need from the knowledge lane's FINAL files (read only), into the portal data folder:
//   assets/actions/sikacalc.js          the lane's quantity calculator (quantity.js) as an ES module, text unchanged apart from the wrapper
//   data/actions/rates/<id>.json        one product record in the shape SikaCalc.calcProduct reads (consumption, pack sizes, trowel table)
//   data/actions/compat/<id>.json       the product's yes / no / conditional rules, each with its exact clause, page and URL
//   data/actions/trees.json             tile adhesive, waterproofing and grout decision trees, trimmed, with the rules they cite
// Usage: node scripts/sika-actions/build_data.mjs [knowledgeDir]
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const PORTAL = path.join(HERE, '..', '..', 'public', 'demo', 'sika-210c0c');
const KN = process.argv[2] || '/home/tech2/klinge-kernel/state/sika/lanes/knowledge';
const rd = (f) => JSON.parse(fs.readFileSync(path.join(KN, f), 'utf8'));
const wr = (rel, o) => { const p = path.join(PORTAL, rel); fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, typeof o === 'string' ? o : JSON.stringify(o)); };
const rm = (d) => { const p = path.join(PORTAL, d); if (p.startsWith(PORTAL + path.sep) && fs.existsSync(p)) fs.rmSync(p, { recursive: true, force: true }); };

// 1. calculator as ESM
const qsrc = fs.readFileSync(path.join(KN, 'calculators', 'quantity.js'), 'utf8');
const head = /\(function \(root, factory\) \{[\s\S]*?\}\)\(typeof self !== 'undefined' \? self : this, function \(\) \{/;
if (!head.test(qsrc) || !/\}\);\s*$/.test(qsrc)) throw new Error('quantity.js wrapper not recognised');
const esm = qsrc.replace(head, 'const SikaCalc = (function () {').replace(/\}\);\s*$/, '})();\nexport default SikaCalc;\n');
wr('assets/actions/sikacalc.js', `// GENERATED by scripts/sika-actions/build_data.mjs from lanes/knowledge/calculators/quantity.js (sha256 ${crypto.createHash('sha256').update(qsrc).digest('hex').slice(0, 16)}). Do not edit; re-run the script.\n` + esm);

// 2. rates
rm('data/actions/rates'); rm('data/actions/compat'); rm('data/actions/safety');
const rates = rd('rates.json');
const KEEP = ['consumption', 'pack_sizes', 'trowel_selection', 'coats', 'layer_thickness', 'density', 'open_time', 'adjustability_time', 'pot_life', 'skin_tack_times', 'cure_times', 'recoat_times'];
let nr = 0;
for (const [id, rec] of Object.entries(rates.products)) {
  const facts = {};
  for (const k of KEEP) if (rec.facts && rec.facts[k] && rec.facts[k].length) facts[k] = rec.facts[k];
  if (!Object.keys(facts).length) continue;
  wr(`data/actions/rates/${id}.json`, { id: rec.id, name: rec.name, brand: rec.brand, product_url: rec.product_url, datasheet: rec.datasheet, rate_status: rec.rate_status, rate_note: rec.rate_note || null, facts });
  nr++;
}
// 3. compat
const compat = rd('compatibility.json');
let nc = 0;
for (const [id, rec] of Object.entries(compat.products)) {
  if (!rec.rules || !rec.rules.length) continue;
  wr(`data/actions/compat/${id}.json`, { id, rules: rec.rules.map((r) => ({ id: r.id, type: r.type, polarity: r.polarity, conditional: !!r.conditional, tags: r.tags || {}, mentions: r.products_mentioned || [], text: r.text, heading: r.heading || null, source: r.source })) });
  nc++;
}
// the portal's safety reader (assistant/apply.js safetyRows) reads each item's source as s = { t, u, v, p, pe }; the lane writes it as source = { doc_type, url, doc_version, page, page_end }
const toS = (o) => {
  if (Array.isArray(o)) return o.map(toS);
  if (o && typeof o === 'object') {
    const r = {}; for (const [k, v] of Object.entries(o)) r[k] = toS(v);
    if (r.source && typeof r.source === 'object' && r.source.url) { r.s = { t: r.source.doc_type, u: r.source.url, v: r.source.doc_version, p: r.source.page, pe: r.source.page_end }; delete r.source; }
    return r;
  }
  return o;
};
// 3b. safety (SDS items with revision dates; only the SDS documents whose name matches the product)
const safety = rd('safety.json');
let ns = 0;
for (const [id, rec] of Object.entries(safety.products)) {
  const all = rec.sds || [];
  if (!all.length) continue;
  const sds = all.filter((x) => x.name_matches_product);
  wr(`data/actions/safety/${id}.json`, { id, sds: toS(sds.length ? sds : all.slice(0, 1)) });
  ns++;
}
// 4. trees
const dt = rd('decision_trees.json');
const used = new Set();
const trimEntry = (e) => {
  const o = { product: e.product };
  if (e.evidence) { o.evidence = e.evidence.slice(0, 2); e.evidence.slice(0, 2).forEach((r) => used.add(r)); }
  if (e.cautions && e.cautions.length) { o.cautions = e.cautions.slice(0, 2); o.cautions.forEach((r) => used.add(r)); }
  if (e.limits && e.limits.length) { o.limits = e.limits.slice(0, 4); o.limits.forEach((r) => used.add(r)); }
  if (e.primers && e.primers.length) { o.primers = e.primers.slice(0, 2); o.primers.forEach((p) => used.add(p.rule)); }
  if (e.primer_products && e.primer_products.length) o.primer_products = e.primer_products;
  if (e.not_stated) o.not_stated = e.not_stated;
  if (e.assumed_membrane) o.assumed_membrane = e.assumed_membrane;
  if (e.because) { o.because = e.because.slice(0, 2); o.because.forEach((r) => used.add(r)); }
  if (e.assumed) o.assumed = e.assumed;
  return o;
};
const leafTrim = (tree) => {
  const out = {};
  for (const [k, l] of Object.entries(tree.leaves)) out[k] = { documented_fit: (l.documented_fit || []).map(trimEntry), partly_documented: (l.partly_documented || []).map(trimEntry), excluded: (l.excluded || []).map(trimEntry) };
  return out;
};
const ad = dt.trees.find((t) => t.id === 'tile-adhesive'), wp = dt.trees.find((t) => t.id === 'waterproofing-membrane'), gr = dt.trees.find((t) => t.id === 'tile-grout');
const q = (t) => t.questions.map((x) => ({ id: x.id, text: x.text, options: x.options.map((o) => ({ id: o.id, label: o.label })) }));
const trees = { schema: 'actions-trees-1', generated_from: 'lanes/knowledge/decision_trees.json (' + dt.generated + ')', adhesive: { questions: q(ad), leaves: leafTrim(ad) }, membrane: { questions: q(wp), leaves: leafTrim(wp) }, grout: { questions: q(gr), products: gr.products.map((p) => ({ product: p.product, name: p.name, says_suitable: (p.says_suitable || []).slice(0, 2), says_not_suitable: (p.says_not_suitable || []).slice(0, 2) })) } };
gr.products.forEach((p) => { (p.says_suitable || []).slice(0, 2).forEach((r) => used.add(r)); (p.says_not_suitable || []).slice(0, 2).forEach((r) => used.add(r)); });
trees.rules = {}; for (const r of used) if (dt.rules[r]) trees.rules[r] = dt.rules[r]; ;
trees.cards = {}; for (const [id, c] of Object.entries(dt.product_cards)) trees.cards[id] = { name: c.name, product_url: c.product_url, pds: c.pds || null };
wr('data/actions/trees.json', trees);
console.log(`rates ${nr} files, compat ${nc} files, safety ${ns} files, trees ${Object.keys(trees.rules).length} rules`);
