// T13 ACCEPT, browser part: calculator on the product page, add to project, bill of materials (table, CSV, print).
import { launch, BASE, newTally, ready } from '../browser.mjs';
const T = newTally('t13_browser');
const b = await launch();
const ctx = await b.newContext({ viewport: { width: 1280, height: 900 }, acceptDownloads: true });
const external = []; const errors = [];
await ctx.route('**/*', (r) => { const u = new URL(r.request().url()); if (u.host === new URL(BASE).host || u.protocol === 'data:' || u.protocol === 'blob:') return r.continue(); external.push(u.href); return r.abort(); });
const page = await ctx.newPage();
page.on('console', (m) => { if (['error', 'warning'].includes(m.type())) errors.push(m.text().slice(0, 160)); });
page.on('pageerror', (e) => errors.push('pageerror ' + e.message));
const type = async (sel, v) => { await page.fill(sel, ''); await page.fill(sel, String(v)); await page.waitForTimeout(150); };
await page.goto(BASE + '#/product/davco-grey-one-potadhesive'); await ready(page); await page.waitForSelector('#calc-out');
T.ok('calculator panel is on the product page', await page.locator('#calc-h').isVisible());
T.ok('nothing worked out before a size is typed', /Enter a size to see quantities/.test(await page.locator('#calc-out').innerText()));
await type('#calc-area', 20);
let o = await page.locator('#calc-out').innerText();
T.ok('20 m2 gives 26.67 L exact', o.includes('26.67 L'), o.slice(0, 300));
T.ok('20 m2 gives 3 x 10 L pails', /3 x 10 L/.test(o), o);
T.ok('basis sentence quoted with its source', /based on a 6mm notched trowel/.test(o) && (await page.locator('#calc-out a[href^="https://aus.sika.com"]').count()) >= 1);
T.ok('status chip beside the figure', /From a published data sheet/.test(o));
await type('#calc-allow', 15);
o = await page.locator('#calc-out').innerText();
T.ok('15% allowance gives 30.67 L and 4 x 10 L', o.includes('30.67 L') && /4 x 10 L/.test(o), o.slice(0, 300));
await type('#calc-allow', 0); await type('#calc-area', 12);
o = await page.locator('#calc-out').innerText();
T.ok('12 m2 gives 16 L and 2 x 10 L among the options', o.includes('16 L') && /2 x 10 L/.test(o));
T.ok('allowance defaults to none and says so', /no allowance added/.test(o));
T.ok('estimate-only line shown', (await page.locator('.finder-calc').innerText()).includes('Estimate only, not an offer. Quantities, not prices. Confirm with the product data sheet and Sika Technical Services before ordering.'));
// add to project, then see the bill of materials
await page.locator('#calc-out button', { hasText: 'Add to project with this quantity' }).first().click();
await page.goto(BASE + '#/projects'); await ready(page); await page.waitForSelector('#bom-table');
const rows = await page.$$eval('#bom-table tbody tr', (trs) => trs.map((tr) => [...tr.children].map((td) => td.innerText.trim())));
T.ok('bill of materials lists the product with quantity and packs', rows.length === 1 && rows[0][1].includes('16 L') && /2 x 10 L/.test(rows[0][2]), JSON.stringify(rows));
const dl = page.waitForEvent('download');
await page.click('#bom-csv'); const d = await dl;
const chunks = []; for await (const c of await d.createReadStream()) chunks.push(c);
const csv = Buffer.concat(chunks).toString('utf8');
const lines = csv.trim().split(/\r?\n/);
const parse = (l) => (l.match(/"((?:[^"]|"")*)"/g) || []).map((x) => x.slice(1, -1).replace(/""/g, '"'));
const csvRows = lines.slice(1, 1 + rows.length).map(parse);
T.ok('CSV rows equal the table rows (product, quantity, packs, basis)', rows.every((r, i) => [0, 1, 2, 3].every((k) => csvRows[i][k] === r[k])), JSON.stringify(csvRows) + ' vs ' + JSON.stringify(rows));
T.ok('CSV carries the estimate line and no prices', csv.includes('Estimate only, not an offer.') && !/\$\s?\d/.test(csv));
T.ok('bill of materials shows the estimate line', (await page.locator('#bom').innerText()).includes('Estimate only, not an offer.'));
await page.emulateMedia({ media: 'print' });
const pdf = await page.pdf({ format: 'A4', printBackground: true });
const pages = (pdf.toString('latin1').match(/\/Type\s*\/Page[^s]/g) || []).length;
T.ok('printed bill of materials is one page', pages === 1, 'pages=' + pages);
await page.emulateMedia({ media: 'screen' });
// a product with no published rate
const idx = await (await fetch(BASE + 'data/finder/r/index.json')).json();
const noRate = Object.keys(idx.noRate)[0];
await page.goto(BASE + '#/product/' + noRate); await ready(page); await page.waitForSelector('.finder-calc');
const t = await page.locator('.finder-calc').innerText();
T.ok('no published rate says "Rate not published, ask Technical Services" and links the data sheet', t.includes('Rate not published, ask Technical Services') && (await page.locator('.finder-calc a[href]').count()) >= 1, t.slice(0, 200));
T.ok('no number shown for an unpublished rate', !/\d+(\.\d+)? (L|kg)\b/.test(t.replace(/Estimate only[^.]*\./, '')));
T.ok('no external requests', external.length === 0, external.join(' '));
T.ok('no console errors', errors.length === 0, errors.join(' | '));
await b.close();
T.done();
