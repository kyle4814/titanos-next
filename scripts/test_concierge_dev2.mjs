// Pins the fresh offer dev half (dev2): schema, counts, synthetic label, zero overlap with the frozen holdout (counts only, never prints holdout text), measured number reproducible. 0 model calls.
import fs from "node:fs";
import crypto from "node:crypto";
import { dev2, runDev2, summary, classes } from "./concierge_dev2.mjs";
import { dev } from "./concierge_dev.mjs";
import { holdout, normalise } from "./concierge_holdout.mjs";
import { questions, shelves } from "./concierge_eval.mjs";
let pass = 0, fail = 0;
const t = (n, ok, d = "") => { if (ok) pass++; else { fail++; console.log("FAIL", n, d); } };
const tset = (q) => [...new Set(key(q).split(" "))].sort().join(" ");
const runs = (q, n = 5) => { const w = key(q).split(" "), o = new Set(); for (let i = 0; i + n <= w.length; i++) o.add(w.slice(i, i + n).join(" ")); return o; };
const overlap = (a, b) => { const ek = new Set(b.map((x) => key(x.q))), ts = new Set(b.map((x) => tset(x.q))), rs = new Set(b.flatMap((x) => [...runs(x.q)])); return a.filter((x) => ek.has(key(x.q)) || ts.has(tset(x.q)) || [...runs(x.q)].some((r) => rs.has(r))).map((x) => x.q); };
const key = (q) => normalise(q).replace(/\s+/g, " ").trim();
const file = new URL("../lib/concierge/dev2.tsv", import.meta.url);
const raw = fs.readFileSync(file, "utf8");
t("at least 120 dev2 asks", dev2.length >= 120, String(dev2.length));
t("pinned count: 207 asks", dev2.length === 207, String(dev2.length));
const offerIds = new Set(shelves.filter((s) => s.id.startsWith("offer:")).map((s) => s.id));
t("every row has exactly 3 non-empty tab fields", raw.split("\n").filter(Boolean).every((l) => { const p = l.split("\t"); return p.length === 3 && p.every((x) => x.trim()); }));
t("every expected shelf is an existing offer shelf", dev2.every((x) => offerIds.has(x.expect)), dev2.filter((x) => !offerIds.has(x.expect)).map((x) => x.expect).join());
const shelvesHit = new Set(dev2.map((x) => x.expect));
t("at least 40 offer shelves covered", shelvesHit.size >= 40, String(shelvesHit.size));
t("pinned: 103 offer shelves covered", shelvesHit.size === 103, String(shelvesHit.size));
t("at least 2 asks per covered shelf", [...shelvesHit].every((s) => dev2.filter((x) => x.expect === s).length >= 2));
t("seats are valid and five or more present", dev2.every((x) => ["guest", "owner", "pro", "agent", "enterprise", "partner"].includes(x.seat)) && new Set(dev2.map((x) => x.seat)).size >= 5);
t("labelled synthetic in its script header", /SYNTHETIC/.test(fs.readFileSync(new URL("./concierge_dev2.mjs", import.meta.url), "utf8")));
t("no duplicate (seat + ask)", new Set(dev2.map((x) => x.seat + "|" + key(x.q))).size === dev2.length);
t("ZERO overlap with holdout (exact, token-set, 5-word run)", overlap(dev2, holdout).length === 0, "overlap count " + overlap(dev2, holdout).length);
t("no ask duplicates a questions.tsv ask", dev2.filter((x) => new Set(questions.map((q) => key(q.q))).has(key(x.q))).length === 0);
t("no ask duplicates a dev.tsv ask", overlap(dev2, dev).length === 0, "count " + overlap(dev2, dev).length);
const res = runDev2(), s = summary(res);
t("every ask got a verdict", res.length === dev2.length);
t("deterministic: two runs identical", JSON.stringify(runDev2()) === JSON.stringify(res));
t("pinned measured number on the int3 router: 134/207 (f79 measured 135; re-pinned 2026-11-10 hand merge, router moved -1)", s.ok === 134 && s.n === 207, s.ok + "/" + s.n);
t("wilson interval brackets the point estimate", s.w[0] < s.ok / s.n && s.ok / s.n < s.w[1]);
t("confusion classes sum to misses", Object.values(classes(s.miss)).reduce((a, b) => a + b, 0) === s.miss.length);
t("mutant: a wrong label is scored a miss", summary([{ ...res[0], ok: false, got: "x" }]).ok === 0);
t("holdout.tsv unchanged (sha256)", crypto.createHash("sha256").update(fs.readFileSync(new URL("../lib/concierge/holdout.tsv", import.meta.url))).digest("hex") === "a2882e79b1f1489689072b5ef25afe4878ec8df1a76bab00c291402a759cc623");
console.log(`concierge dev2: ${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
