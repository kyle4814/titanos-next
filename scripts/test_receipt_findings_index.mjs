import fs from "node:fs"; import os from "node:os"; import path from "node:path"; import assert from "node:assert/strict";
import { buildIndex, summarise, render, chunkOf, coverage } from "./receipt_findings_index.mjs";
const d = fs.mkdtempSync(path.join(os.tmpdir(), "rfi-")), b = path.join(d, "briefs"); fs.mkdirSync(b);
const w = (n, t) => fs.writeFileSync(path.join(d, n), t);
w("FILL_f1_c2_cancel_term_RECEIPT.md", "x\n1. NEW FINDING, NOT FIXED: refund webhook drops events\n- WOULD-FLIP: real D1 deploy\nCANCELOK OK fine\n");
w("FILL_f2_c3_undo_race_RECEIPT.md", "Candidate next row: webhook refund retry queue\nUNDO FAILED why\n");
w("FILL_f3_misc_RECEIPT.md", "chunk c7 note\nNOT FIXED: zebra anomaly\nZ PARTIAL half\n");
w("NOTES.md", "NEW FINDING ignored\n");
for (const n of ["f1_c2_cancel_term", "f2_c3_undo_race", "f9_c4_webhook_refund_retry"]) fs.writeFileSync(path.join(b, n + ".md"), "b");
const idx = buildIndex(d, b), s = summarise(idx);
assert.equal(idx.files, 3); assert.equal(idx.briefs, 3);
assert.equal(chunkOf("f3_misc", "a\nchunk c7 here"), "c7"); assert.equal(chunkOf("f1_c10_x", ""), "c10"); assert.equal(chunkOf("f1_c11_x", ""), "unassigned");
assert.equal(s.chunks.c2.unfixed, 1); assert.equal(s.chunks.c2.pendingLive, 1); assert.equal(s.chunks.c3.unfixed, 2);
assert.equal(s.chunks.c7.unfixed, 2); assert.equal(s.unfixed, 5);
// refund+webhook+retry tokens covered by f9 brief; zebra uncovered; own brief never counts
const f1 = idx.rows.find((r) => r.kind === "NEW FINDING"); assert.equal(f1.line, 2);
assert.equal(f1.covered.length, 1);
const cand = idx.rows.find((r) => r.kind === "Candidate next row"); assert.match(cand.covered[0].brief, /f9_c4/); assert.match(cand.covered[0].method, /^keyword/);
assert.equal(coverage({ id: "f1_x", text: "see f9 for this" }, ["f9_c4_webhook_refund_retry"])[0].method, "id-ref");
assert.equal(coverage({ id: "f9_c4_webhook_refund_retry", text: "webhook refund retry" }, ["f9_c4_webhook_refund_retry"]).length, 0);
assert.ok(idx.rows.some((r) => r.kind === "PARTIAL/FAILED final" && r.line === 2));
assert.ok(!idx.rows.some((r) => r.text.includes("ignored")));
const md = render(idx); assert.match(md, /PENDING LIVE/); assert.match(md, /FILL_f3_misc_RECEIPT\.md:2;/);
console.log("test_receipt_findings_index OK"); fs.rmSync(d, { recursive: true });
